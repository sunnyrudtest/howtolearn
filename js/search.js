/* ==========================================================================
   Search: find any topic across every course, down to a single step.

   Two layers:
     PL.searchEngine  — pure text matching and ranking (no DOM).
     PL.searchPage    — the #/search page, plus the "/" and Ctrl+K shortcuts.

   What gets searched: each lesson's title, tagline, topics, chapter and course
   (all in js/courses.js), plus keywords and the text of every step from
   js/search-index.js. The step index is generated by
   tools/build-search-index.js and is only downloaded when search is opened;
   until it arrives, search works on the catalog alone.
   ========================================================================== */
(function () {
  'use strict';

  /* ======================= Text: normalise, tokenise, stem ======================= */

  // US spellings → the UK spellings the lessons use.
  const SPELLING = { neighbor: 'neighbour', neighbors: 'neighbours', color: 'colour', colors: 'colours', behavior: 'behaviour', behaviors: 'behaviours', labeled: 'labelled', modeling: 'modelling', center: 'centre', gray: 'grey' };
  const STOP = new Set(['a', 'an', 'the', 'to', 'of', 'is', 'are', 'am', 'be', 'it', 'its', 'how', 'what', 'whats', 'why', 'when', 'which', 'who',
    'do', 'does', 'did', 'i', 'me', 'my', 'we', 'you', 'your', 'can', 'learn', 'learning', 'about', 'teach', 'explain', 'show', 'please', 'with', 'on', 'for', 'this', 'that', 'work', 'works', 'use', 'using']);
  // "learning" is a stop word in "learn about loops", but not in "machine learning".
  const KEEP_PAIRS = new Set(['machine learning', 'deep learning', 'learning rate', 'how ai learns']);

  const fold = (str) => String(str || '').toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '')
    .replace(/[‘’']/g, '').replace(/[−–]/g, '-').replace(/×/g, '*');

  function stem(t) {
    if (Object.prototype.hasOwnProperty.call(SPELLING, t)) t = SPELLING[t];
    if (t.length <= 3 || !/^[a-z]+$/.test(t)) return t;
    if (t.length > 5) t = t.replace(/iz(e|es|ed|ing|ation|ations)$/, 'is$1');
    if (/ies$/.test(t) && t.length > 4) t = t.slice(0, -3) + 'y';
    else if (/(sses|xes|ches|shes)$/.test(t)) t = t.slice(0, -2);
    else if (/[^su]s$/.test(t)) t = t.slice(0, -1);
    const rules = [['ations', 6], ['ation', 6], ['ions', 6], ['ion', 6], ['ive', 6], ['ing', 6], ['ed', 6], ['ate', 7], ['ly', 6], ['al', 7], ['er', 6]];
    for (const [suf, min] of rules) {
      if (t.length >= min && t.endsWith(suf) && t.length - suf.length >= 3) { t = t.slice(0, -suf.length); break; }
    }
    if (t.length > 4 && t.endsWith('e')) t = t.slice(0, -1);
    return t;
  }

  const WORD = /[a-z0-9_]+(?:-[a-z0-9_]+)*|[+\-*/%=<>!&|@^]+/g;
  const isWord = (t) => /^[a-z0-9_]/.test(t);
  /** Text → list of stems. Hyphenated words give the whole word and its parts.
      If `raw` is given, the unstemmed word behind each stem is pushed to it too. */
  function tokens(text, raw) {
    const out = [];
    const s = fold(text);
    let m;
    WORD.lastIndex = 0;
    while ((m = WORD.exec(s))) {
      const w = m[0];
      const parts = isWord(w) && w.includes('-') ? [w.replace(/-/g, ''), ...w.split('-').filter(Boolean)] : [w];
      parts.forEach((x) => {
        out.push(isWord(x) ? stem(x) : x);
        if (raw) raw.push(x);
      });
    }
    return out;
  }

  /** Edit distance with an early exit once it must exceed `max`. */
  function within(a, b, max) {
    if (Math.abs(a.length - b.length) > max) return false;
    // Damerau–Levenshtein (with swaps of neighbouring letters), two rows back.
    let pp = null;
    let prev = Array.from({ length: b.length + 1 }, (_, j) => j);
    for (let i = 1; i <= a.length; i++) {
      const cur = [i];
      let best = i;
      for (let j = 1; j <= b.length; j++) {
        const cost = a[i - 1] === b[j - 1] ? 0 : 1;
        let v = Math.min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + cost);
        if (pp && j > 1 && a[i - 1] === b[j - 2] && a[i - 2] === b[j - 1]) v = Math.min(v, pp[j - 2] + 1);
        cur[j] = v;
        if (v < best) best = v;
      }
      if (best > max) return false;
      pp = prev;
      prev = cur;
    }
    return prev[b.length] <= max;
  }

  /* ======================= Engine ======================= */

  // Field weights: how much a match in each place counts.
  const F = { title: 10, keyword: 7, topic: 6, tagline: 4, chapter: 2.5, step: 4, intro: 1.2, recap: 1 };
  // Where a match means the lesson is *about* the query. The chapter and course
  // names still add to the score, but "python" alone shouldn't list 50 lessons.
  const ABOUT = new Set(['title', 'keyword', 'topic', 'tagline']);

  /**
   * docs: [{ id, title, tagline, topics[], keywords[], chapter, course, steps: [[title, intro]], recap[] }]
   * soon: [{ course, courseId, title }]  — planned topics that have no lesson yet
   * groups: [{ kind: 'course' | 'chapter', title, … }]  — matched by name only
   */
  function createEngine(docs, soon, groups) {
    const vocab = new Map(); // stem → [[docIndex, field, step]]
    const words = new Map(); // unstemmed word → stem, for spotting typos
    const phrases = docs.map(() => ({})); // per doc: field → [" stem stem "]
    const titleTokens = docs.map((d) => tokens(d.title).filter((t) => isWord(t) && !STOP.has(t)));
    const titleFirst = docs.map((d) => tokens(d.title)[0]);

    docs.forEach((d, di) => {
      const add = (field, text, step) => {
        const raw = [];
        const ts = tokens(text, raw);
        if (!ts.length) return;
        raw.forEach((w, i) => { if (isWord(w) && w.length >= 4) words.set(w, ts[i]); });
        // Phrases skip small words, as queries do: "train a model" matches "training model".
        const content = ts.filter((t, i) => !STOP.has(raw[i]) && !STOP.has(t));
        (phrases[di][field] = phrases[di][field] || []).push({ str: ' ' + (content.length ? content : ts).join(' ') + ' ', step });
        new Set(ts).forEach((t) => {
          if (!vocab.has(t)) vocab.set(t, []);
          vocab.get(t).push([di, field, step]);
        });
      };
      add('title', d.title);
      d.keywords.forEach((k) => add('keyword', k));
      d.topics.forEach((k) => add('topic', k));
      add('tagline', d.tagline);
      add('chapter', d.chapter + ' ' + d.course);
      d.steps.forEach(([t, intro], si) => { add('step', t, si); add('intro', intro, si); });
      d.recap.forEach((r) => add('recap', r));
    });
    const terms = [...vocab.keys()];
    const wordList = [...words.keys()];
    const groupTokens = (groups || []).map((g) => [...new Set(tokens(g.title).filter((t) => !STOP.has(t) && t !== '&'))]);

    /** Which vocabulary terms a query token matches, and how strongly. */
    const expandCache = new Map();
    function expand(q, isLast, raw) {
      const key = (isLast ? '1' : '0') + q + '|' + raw;
      if (expandCache.has(key)) return expandCache.get(key);
      if (expandCache.size > 500) expandCache.clear();
      const out = new Map();
      expandCache.set(key, out);
      if (vocab.has(q)) out.set(q, 1);
      if (!isWord(q)) return out;
      if (q.length >= (isLast ? 2 : 3)) {
        for (const t of terms) if (t !== q && t.startsWith(q)) out.set(t, isLast ? 0.8 : 0.7);
      }
      // Typos only for words we don't know: "list" must not also find "lost".
      // Compared on the unstemmed word, so swapped letters count once ("recursoin").
      const typo = out.size ? 0 : raw.length >= 8 ? 2 : raw.length >= 5 ? 1 : 0;
      if (typo) {
        for (const w of wordList) if (within(raw, w, typo)) out.set(words.get(w), 0.55);
      }
      return out;
    }

    function parse(raw) {
      const text = fold(raw).slice(0, 120);
      const rawWords = [];
      let ts = tokens(text, rawWords);
      const rawOf = {};
      ts.forEach((t, i) => { if (!(t in rawOf)) rawOf[t] = rawWords[i]; });
      const folded = text.trim().replace(/\s+/g, ' ');
      const keepAll = [...KEEP_PAIRS].some((p) => folded.includes(p));
      const content = ts.filter((t) => !STOP.has(rawOf[t]) && !STOP.has(t));
      if (!keepAll && content.length) ts = content;
      ts = [...new Set(ts)].slice(0, 8);
      return { ts, raws: ts.map((t) => rawOf[t]), phrase: ts.length > 1 ? ' ' + ts.join(' ') + ' ' : null, endsMidWord: /[a-z0-9]$/i.test(String(raw)) };
    }

    /** Courses and chapters whose name the query spells out ("functions", "python"). */
    function matchGroups(ts, endsMidWord) {
      const last = ts[ts.length - 1];
      return (groups || []).filter((g, gi) => {
        const gt = groupTokens[gi];
        if (!gt.length) return false;
        const hit = (q) => gt.includes(q) || (endsMidWord && q === last && q.length >= 3 && gt.some((t) => t.startsWith(q)));
        const covered = gt.filter((t) => ts.some((q) => t === q || (endsMidWord && q === last && q.length >= 3 && t.startsWith(q)))).length;
        return ts.every(hit) && covered / gt.length >= 0.5;
      });
    }

    function search(raw) {
      const { ts, raws, phrase, endsMidWord } = parse(raw);
      if (!ts.length) return { query: raw, tokens: [], groups: [], topics: [], mentions: [], partial: [], soon: [], matched: new Set() };
      const n = ts.length;
      const matched = new Set(); // vocabulary terms that matched (for highlighting)
      const per = docs.map(() => ({ best: new Array(n).fill(0), about: new Array(n).fill(0), steps: {} }));

      ts.forEach((q, qi) => {
        const ex = expand(q, endsMidWord && qi === n - 1, raws[qi]);
        ex.forEach((strength, term) => {
          matched.add(term);
          for (const [di, field, step] of vocab.get(term)) {
            const p = per[di];
            const v = strength * F[field];
            if (v > p.best[qi]) p.best[qi] = v;
            if (ABOUT.has(field) && v > p.about[qi]) p.about[qi] = v;
            if (step != null) {
              const s = (p.steps[step] = p.steps[step] || { best: new Array(n).fill(0), title: false });
              if (v > s.best[qi]) s.best[qi] = v;
              if (field === 'step') s.title = true;
            }
          }
        });
      });

      const qExact = ' ' + ts.join(' ') + ' ';
      const results = [];
      docs.forEach((d, di) => {
        const p = per[di];
        const covered = p.best.filter((v) => v > 0).length;
        if (!covered) return;
        const ph = phrases[di];
        const has = (field, str) => (ph[field] || []).some((x) => x.str.includes(str));
        const eq = (field) => (ph[field] || []).some((x) => x.str === qExact);
        let bonus = 0;
        if (eq('title')) bonus += 40;
        // Every word of a short title matched, e.g. "lis" while typing "Lists".
        else if (titleTokens[di].length && titleTokens[di].length <= n + 1 && titleTokens[di].every((t) => matched.has(t))) bonus += 12;
        if (matched.has(titleFirst[di])) bonus += 2;
        else if (phrase && has('title', phrase)) bonus += 15;
        if (eq('keyword')) bonus += 26;
        else if (phrase && has('keyword', phrase)) bonus += 10;
        if (eq('topic')) bonus += 14;
        else if (phrase && has('topic', phrase)) bonus += 8;
        if (phrase && has('tagline', phrase)) bonus += 4;

        const base = p.best.reduce((a, b) => a + b, 0);
        const aboutCovered = p.about.filter((v) => v > 0).length;

        // Steps worth showing: they cover every word, or match in the step title.
        const steps = Object.keys(p.steps).map((k) => {
          const s = p.steps[k];
          const cov = s.best.filter((v) => v > 0).length;
          let score = s.best.reduce((a, b) => a + b, 0);
          if (phrase && (ph.step || []).some((x) => x.step === +k && x.str.includes(phrase))) score += 6;
          if (phrase && (ph.intro || []).some((x) => x.step === +k && x.str.includes(phrase))) score += 2.5;
          return { index: +k, score, full: cov === n, title: s.title };
        }).filter((s) => s.full && (s.title || s.score >= F.intro * n * 0.99));
        steps.sort((a, b) => b.score - a.score);

        const full = covered === n;
        const stepBoost = steps.length ? Math.min(6, steps[0].score * 0.5) : 0;
        results.push({
          doc: d,
          score: (base + bonus + stepBoost) * (full ? 1 : 0.3 * (covered / n)),
          full,
          about: aboutCovered === n,
          steps: steps.slice(0, 3).sort((a, b) => a.index - b.index),
          stepCount: steps.length,
        });
      });
      results.sort((a, b) => b.score - a.score || a.doc.order - b.doc.order);

      const topics = results.filter((r) => r.full && r.about);
      const mentions = results.filter((r) => r.full && !r.about && r.steps.length);
      const partial = topics.length || mentions.length ? [] : results.filter((r) => !r.full).slice(0, 6);

      const soonHits = soon.filter((t) => {
        const st = ' ' + tokens(t.title).join(' ') + ' ';
        return ts.every((q) => st.includes(' ' + q + ' ') || (endsMidWord && q === ts[n - 1] && q.length >= 2 && st.includes(' ' + q)));
      });
      return { query: raw, tokens: ts, groups: matchGroups(ts, endsMidWord), topics, mentions, partial, soon: soonHits, matched };
    }

    /** A close spelling of the whole query, for "Did you mean…?". */
    function suggest(raw) {
      const q = fold(raw).trim();
      if (q.length < 3) return null;
      let best = null;
      const consider = (label) => {
        const f = fold(label);
        if (f === q) return;
        const max = q.length >= 8 ? 3 : 2;
        for (let d = 1; d <= max; d++) {
          if (within(q, f, d)) { if (!best || d < best.d) best = { d, label }; return; }
        }
      };
      docs.forEach((d) => { consider(d.title); d.keywords.forEach(consider); d.topics.forEach(consider); });
      return best ? best.label : null;
    }

    return { search, suggest, size: docs.length };
  }

  /** Highlight words in `text` whose stem is in `matched`. Returns safe HTML. */
  function highlight(text, matched) {
    const src = String(text || '');
    if (!matched || !matched.size) return PL.esc(src);
    let out = '';
    let last = 0;
    const re = /[A-Za-z0-9_]+/g;
    let m;
    while ((m = re.exec(src))) {
      const st = stem(fold(m[0]));
      if (matched.has(st)) {
        out += PL.esc(src.slice(last, m.index)) + '<mark>' + PL.esc(m[0]) + '</mark>';
        last = m.index + m[0].length;
      }
    }
    return out + PL.esc(src.slice(last));
  }

  /** ~150 characters of `text` around the first highlighted word. */
  function snippet(text, matched, len = 150) {
    const src = String(text || '');
    if (src.length <= len) return highlight(src, matched);
    const re = /[A-Za-z0-9_]+/g;
    let m, at = 0;
    while ((m = re.exec(src))) { if (matched.has(stem(fold(m[0])))) { at = m.index; break; } }
    let start = Math.max(0, at - Math.round(len * 0.35));
    if (start > 0) { const sp = src.indexOf(' ', start); start = sp > -1 && sp < at ? sp + 1 : start; }
    let end = Math.min(src.length, start + len);
    if (end < src.length) { const sp = src.lastIndexOf(' ', end); if (sp > at) end = sp; }
    return (start > 0 ? '…' : '') + highlight(src.slice(start, end), matched) + (end < src.length ? '…' : '');
  }

  PL.searchEngine = { createEngine, tokens, stem, highlight, snippet };

  /* ======================= Data: catalog + lazily loaded step index ======================= */

  let indexPromise = null;
  function loadIndex() {
    if (PL.searchIndex) return Promise.resolve(PL.searchIndex);
    if (indexPromise) return indexPromise;
    indexPromise = new Promise((resolve, reject) => {
      const sc = document.createElement('script');
      sc.src = 'js/search-index.js';
      sc.async = true;
      sc.onload = () => (PL.searchIndex ? resolve(PL.searchIndex) : reject(new Error('Search index did not load')));
      sc.onerror = () => { indexPromise = null; sc.remove(); reject(new Error('Could not load the search index')); };
      document.head.appendChild(sc);
    });
    return indexPromise;
  }

  /** An engine over the whole catalog, plus the step index if it has loaded. */
  function fromCatalog() {
    const extra = (PL.searchIndex && PL.searchIndex.lessons) || {};
    const docs = [];
    const soon = [];
    const groups = [];
    let order = 0;
    (PL.courses || []).forEach((course) => {
      if (course.status !== 'live') {
        (course.topics || []).forEach((t) => soon.push({ course: course.title, courseId: course.id, title: t, color: course.color }));
        return;
      }
      groups.push({ kind: 'course', title: course.title, course });
      course.chapters.forEach((ch) => groups.push({ kind: 'chapter', title: ch.title, course, chapter: ch }));
      PL.courseLessons(course.id).forEach((meta) => {
        if (meta.soon) { soon.push({ course: course.title, courseId: course.id, title: meta.title, color: course.color }); return; }
        const x = extra[meta.id] || {};
        docs.push({
          id: meta.id, order: order++, meta,
          title: meta.title, tagline: meta.tagline || '', topics: meta.topics || [],
          keywords: x.k || [], chapter: meta.chapter.title, course: course.title,
          steps: x.s || [], recap: x.r || [], related: x.rel || [],
        });
      });
    });
    return createEngine(docs, soon, groups);
  }
  PL.searchEngine.fromCatalog = fromCatalog;

  let engineCache = { withIndex: null, engine: null };
  function engine() {
    const withIndex = !!PL.searchIndex;
    if (!engineCache.engine || engineCache.withIndex !== withIndex) engineCache = { withIndex, engine: fromCatalog() };
    return engineCache.engine;
  }

  /* ======================= Recent searches (this device only) ======================= */

  const RECENT_KEY = 'howtolearn:search';
  const recent = {
    list() { try { const v = JSON.parse(localStorage.getItem(RECENT_KEY)); return Array.isArray(v) ? v.filter((x) => typeof x === 'string').slice(0, 6) : []; } catch (e) { return []; } },
    add(q) {
      q = String(q || '').trim().slice(0, 60);
      if (q.length < 2) return;
      const l = [q, ...this.list().filter((x) => x.toLowerCase() !== q.toLowerCase())].slice(0, 6);
      try { localStorage.setItem(RECENT_KEY, JSON.stringify(l)); } catch (e) { /* storage unavailable */ }
    },
    clear() { try { localStorage.removeItem(RECENT_KEY); } catch (e) { /* storage unavailable */ } },
  };

  /* ======================= Page ======================= */

  const { h, icons } = PL;
  const SEARCH_ICON = PL.ui.searchIcon;
  const ARROW = icons.next;
  const POPULAR = ['Variables', 'For loops', 'Functions', 'Recursion', 'Dictionaries', 'Classes', 'Big O', 'Vectors', 'Dot product', 'Gradient descent', 'Neuron', 'Probability', 'Bayes', 'Next-word prediction'];

  const hashFor = (q, c) => {
    const p = new URLSearchParams();
    if (q) p.set('q', q);
    if (c && c !== 'all') p.set('c', c);
    const s = p.toString();
    return '#/search' + (s ? '?' + s : '');
  };
  const parseHash = () => {
    const i = location.hash.indexOf('?');
    const p = new URLSearchParams(i > -1 ? location.hash.slice(i + 1) : '');
    return { q: (p.get('q') || '').slice(0, 120), c: p.get('c') || 'all' };
  };

  function stateOf(meta) {
    const p = PL.progress.lesson(meta.id);
    const frac = PL.lessonFrac(meta);
    return p.done ? { label: 'Review', cls: 'done', note: '✓ Completed' } : frac > 0 ? { label: 'Continue', cls: 'going', note: `${Math.round(frac * 100)}% done` } : { label: 'Start', cls: '', note: '' };
  }
  const courseTag = (meta) => {
    const c = PL.course(meta.course);
    return h('span', { class: 'sr-course', style: { '--c': c.color } }, c.title);
  };
  const where = (meta) => `Chapter ${meta.chapter.num} · Lesson ${meta.n}`;
  const lessonHref = (id, step) => '#/lesson/' + id + (step != null ? '/' + (step + 1) : '');

  let cleanups = [];
  let st = null; // live page state

  function render(initial) {
    destroy();
    const root = document.getElementById('app');
    const nav = PL.ui.nav([{ label: 'All courses', href: '#/' }], cleanups, { searchActive: true });

    const input = h('input', {
      type: 'search', class: 'sr-input', id: 'sr-input', placeholder: 'Search any topic: loops, vectors, gradient descent…',
      autocomplete: 'off', autocapitalize: 'off', spellcheck: 'false', enterkeyhint: 'search', maxlength: '120',
      'aria-label': 'Search lessons', 'aria-describedby': 'sr-status', 'aria-controls': 'sr-results',
    });
    input.value = initial.q;
    const clearBtn = h('button', { type: 'button', class: 'sr-clear', 'aria-label': 'Clear search', html: icons.close, hidden: !initial.q });
    const form = h('form', { class: 'sr-box', role: 'search', onSubmit: (e) => { e.preventDefault(); openActive(); } },
      h('span', { class: 'sr-ico', html: SEARCH_ICON }), input, clearBtn, h('kbd', { class: 'sr-kbd', 'aria-hidden': 'true' }, 'Esc'));
    const status = h('p', { class: 'sr-status', id: 'sr-status', role: 'status', 'aria-live': 'polite' });
    const filters = h('div', { class: 'sr-filters', role: 'group', 'aria-label': 'Filter by course' });
    const results = h('div', { class: 'sr-results', id: 'sr-results' });

    const page = h('section', { class: 'wrap sr-page' },
      h('h1', { class: 'sr-title' }, 'What do you want to learn?'),
      h('p', { class: 'sr-sub' }, 'Search every lesson in every course — right down to a single step.'),
      form, h('div', { class: 'sr-bar' }, status, filters), results);

    root.replaceChildren(h('div', { class: 'home' }, nav, h('main', { id: 'main' }, page), PL.ui.footer(() => render(parseHash()))));
    window.scrollTo(0, 0);

    st = { input, clearBtn, status, filters, results, q: initial.q, c: initial.c, active: -1, hits: [], showAll: false, raf: 0 };

    const onInput = () => {
      st.q = input.value;
      st.showAll = false;
      clearBtn.hidden = !st.q;
      cancelAnimationFrame(st.raf);
      st.raf = requestAnimationFrame(update);
    };
    input.addEventListener('input', onInput);
    input.addEventListener('keydown', (e) => {
      if (e.key === 'ArrowDown' || e.key === 'ArrowUp') { e.preventDefault(); move(e.key === 'ArrowDown' ? 1 : -1); }
      else if (e.key === 'Escape') {
        e.preventDefault();
        if (input.value) { input.value = ''; onInput(); } else input.blur();
      }
    });
    clearBtn.addEventListener('click', () => { input.value = ''; onInput(); input.focus(); });
    cleanups.push(() => cancelAnimationFrame(st && st.raf));

    update();
    // Don't pop the phone keyboard over results that came from a shared link.
    if (!initial.q || window.matchMedia('(min-width: 761px)').matches) input.focus({ preventScroll: true });
    if (!PL.searchIndex) {
      loadIndex().then(() => { if (st && st.input === input) update(); }).catch(() => {
        if (st && st.input === input) { st.indexFailed = true; update(); }
      });
    }
  }

  function update() {
    if (!st) return;
    const q = st.q.trim();
    const url = hashFor(q, st.c);
    if (location.hash !== url) history.replaceState(null, '', url);
    document.title = q ? `${q} · Search · HowToLearn` : 'Search · HowToLearn';
    st.active = -1;
    if (!q) { st.filters.replaceChildren(); st.status.textContent = ''; renderEmpty(); return; }

    const eng = engine();
    const res = eng.search(q);
    const inCourse = (r) => st.c === 'all' || r.doc.meta.course === st.c;
    const counts = {};
    [...res.topics, ...res.mentions].forEach((r) => { counts[r.doc.meta.course] = (counts[r.doc.meta.course] || 0) + 1; });
    if (st.c !== 'all' && !counts[st.c]) st.c = 'all';
    renderFilters(counts, res.topics.length + res.mentions.length);

    const topics = res.topics.filter(inCourse);
    const mentions = res.mentions.filter(inCourse);
    const groups = res.groups.filter((g) => st.c === 'all' || g.course.id === st.c);
    const total = topics.length + mentions.length;
    st.status.textContent = total
      ? `${topics.length ? plural(topics.length, 'lesson') + ' about this' : ''}${topics.length && mentions.length ? ' · ' : ''}${mentions.length ? plural(mentions.length, 'more lesson') + ' mention' + (mentions.length === 1 ? 's' : '') + ' it' : ''}`
      : groups.length ? '' : res.partial.length ? 'No lesson matches every word.' : 'No lessons found.';

    const parts = [];
    const groupSec = groups.length ? h('section', { class: 'sr-sec' }, h('h2', null, groups.length === 1 ? (groups[0].kind === 'course' ? 'Whole course' : 'Whole chapter') : 'Courses and chapters'),
      h('div', { class: 'sr-grid' }, groups.map(groupCard))) : null;
    // A course name ("python", "math") is a request for the course, not for one lesson that says it.
    const courseFirst = groups.some((g) => g.kind === 'course');
    if ((!topics.length || courseFirst) && groupSec) parts.push(groupSec);
    if (topics.length) {
      if (!courseFirst) parts.push(bestCard(topics[0], res.matched));
      if (groupSec && !courseFirst) parts.push(groupSec);
      if (topics.length > 1 || courseFirst) {
        const rest = courseFirst ? topics : topics.slice(1);
        const shown = st.showAll ? rest : rest.slice(0, 8);
        parts.push(h('section', { class: 'sr-sec' }, h('h2', null, courseFirst ? 'Lessons about this' : topics.length === 2 ? 'Another lesson about this' : 'More lessons about this'),
          h('div', { class: 'sr-grid' }, shown.map((r) => card(r, res.matched))),
          rest.length > shown.length ? PL.btn(`Show ${rest.length - shown.length} more`, { variant: 'soft', class: 'sr-more', onClick: () => { st.showAll = true; update(); } }) : null));
      }
    }
    if (mentions.length) {
      parts.push(h('section', { class: 'sr-sec' }, h('h2', null, topics.length ? 'Also found inside other lessons' : 'Found inside these lessons'),
        h('div', { class: 'sr-mentions' }, mentions.slice(0, 10).map((r) => mentionRow(r, res.matched)))));
    }
    if (!total && !groups.length) parts.push(noResults(q, res, eng));
    if (res.soon.length) parts.push(soonNote(res.soon, topics.length > 0));
    // The no-results panel says it in words already; keep the status for screen readers.
    st.status.classList.toggle('sr-only', !total && !groups.length);
    if (st.indexFailed) parts.push(h('p', { class: 'sr-warn' }, 'Searching titles and topics only — the full lesson text couldn\'t load. Check your connection and reload.'));
    st.results.replaceChildren(...parts);
    st.hits = [...st.results.querySelectorAll('[data-hit]')];
  }

  const plural = (n, word) => `${n} ${word}${n === 1 ? '' : 's'}`;

  function renderFilters(counts, total) {
    const live = (PL.courses || []).filter((c) => counts[c.id]);
    if (live.length < 2) { st.filters.replaceChildren(); return; }
    const chip = (id, label, n, color) => h('button', {
      type: 'button', class: 'sr-chip' + (st.c === id ? ' on' : ''), 'aria-pressed': st.c === id ? 'true' : 'false', style: color ? { '--c': color } : null,
      onClick: () => { st.c = id; st.showAll = false; update(); },
    }, label, h('span', { class: 'n' }, String(n)));
    st.filters.replaceChildren(chip('all', 'All', total), ...live.map((c) => chip(c.id, c.title, counts[c.id], c.color)));
  }

  function stepList(r, matched, all) {
    const d = r.doc;
    const hitSet = new Set(r.steps.map((s) => s.index));
    const items = all ? d.steps.map((s, i) => i) : r.steps.map((s) => s.index);
    if (!items.length) return null;
    return h('ol', { class: 'sr-steps' + (all ? ' all' : '') }, items.map((i) => {
      const [title, intro] = d.steps[i];
      const hit = hitSet.has(i);
      return h('li', { class: hit ? 'hit' : '' },
        h('a', { href: lessonHref(d.id, i), onClick: () => recent.add(st.q) },
          h('span', { class: 'sr-sn' }, String(i + 1)),
          h('span', { class: 'sr-st' },
            h('span', { class: 'sr-stt', html: highlight(title, matched) }),
            hit && !all ? h('span', { class: 'sr-sni', html: snippet(intro, matched, 130) }) : null)));
    }));
  }

  function bestCard(r, matched) {
    const d = r.doc, meta = d.meta;
    const state = stateOf(meta);
    const prev = PL.liveLessons(meta.course)[PL.liveLessons(meta.course).findIndex((l) => l.id === d.id) - 1];
    const next = PL.nextLesson(d.id);
    const rel = d.related.map(PL.lessonMeta).filter(Boolean);
    const linkTo = (m) => h('a', { class: 'sr-link', href: lessonHref(m.id), onClick: () => recent.add(st.q) }, m.title);

    return h('section', { class: 'sr-sec' }, h('h2', null, 'Best match'),
      h('article', { class: 'sr-best', style: { '--c': meta.color, '--cs': meta.soft } },
        h('div', { class: 'sr-best-head' },
          h('div', { class: 'lc-art sr-art', html: PL.art[d.id] || '' }),
          h('div', { class: 'sr-best-text' },
            h('div', { class: 'sr-kick' }, courseTag(meta), h('span', null, where(meta)), h('span', null, `${meta.steps} steps · ~${meta.minutes} min`),
              state.note ? h('span', { class: 'sr-state ' + state.cls }, state.note) : null),
            h('h3', null, h('a', { class: 'sr-main', href: lessonHref(d.id), 'data-hit': '', onClick: () => recent.add(st.q), html: highlight(d.title, matched) })),
            h('p', { class: 'sr-tag', html: highlight(d.tagline, matched) }),
            h('div', { class: 'lc-topics' }, d.topics.map((t) => h('span', { html: highlight(t, matched) })))),
          h('a', { class: 'btn btn-accent sr-go', href: lessonHref(d.id), tabindex: '-1', onClick: () => recent.add(st.q) }, h('span', { class: 'btn-lbl' }, state.label), h('span', { class: 'btn-ico', html: ARROW }))),
        d.steps.length ? h('div', { class: 'sr-inside' },
          h('div', { class: 'sr-lbl' }, 'Inside this lesson', r.steps.length ? h('span', null, ` · ${plural(r.steps.length, 'step')} match`) : null),
          stepList(r, matched, true)) : null,
        h('div', { class: 'sr-path' },
          prev ? h('div', null, h('span', { class: 'sr-lbl' }, 'Previous lesson'), linkTo(prev)) : h('div', null, h('span', { class: 'sr-lbl' }, 'Previous lesson'), h('span', { class: 'sr-none' }, 'None — this is lesson 1')),
          next ? h('div', null, h('span', { class: 'sr-lbl' }, 'Next lesson'), linkTo(next)) : null,
          rel.length ? h('div', { class: 'sr-rel' }, h('span', { class: 'sr-lbl' }, 'Related'),
            h('div', { class: 'sr-relx' }, rel.map((m) => h('a', { class: 'sr-relchip', href: lessonHref(m.id), style: { '--c': PL.course(m.course).color }, onClick: () => recent.add(st.q) },
              h('span', { class: 'dot' }), m.title, h('small', null, PL.course(m.course).title))))) : null)));
  }

  function card(r, matched) {
    const d = r.doc, meta = d.meta;
    const state = stateOf(meta);
    return h('article', { class: 'sr-card', style: { '--c': meta.color, '--cs': meta.soft } },
      h('div', { class: 'lc-art sr-art sm', html: PL.art[d.id] || '' }),
      h('div', { class: 'sr-card-body' },
        h('div', { class: 'sr-kick' }, courseTag(meta), h('span', null, where(meta)), state.note ? h('span', { class: 'sr-state ' + state.cls }, state.note) : null),
        h('h3', null, h('a', { class: 'sr-main', href: lessonHref(d.id), 'data-hit': '', onClick: () => recent.add(st.q), html: highlight(d.title, matched) })),
        h('p', { class: 'sr-tag', html: highlight(d.tagline, matched) }),
        r.steps.length ? stepList({ doc: d, steps: r.steps.slice(0, 2) }, matched, false) : null));
  }

  function groupCard(g) {
    const c = g.course;
    if (g.kind === 'course') {
      const st2 = PL.ui.courseStats(c.id);
      return h('a', { class: 'sr-group', href: '#/course/' + c.id, 'data-hit': '', style: { '--c': c.color, '--cs': c.soft } },
        h('div', { class: 'sr-cc-art', html: PL.courseArt[c.id] || '' }),
        h('div', { class: 'sr-group-body' },
          h('div', { class: 'sr-kick' }, h('span', { class: 'sr-course', style: { '--c': c.color } }, 'Course'), h('span', null, `${c.chapters.length} chapters · ${st2.total} lessons`),
            st2.started ? h('span', { class: 'sr-state going' }, `${st2.done} done`) : null),
          h('h3', null, c.title), h('p', { class: 'sr-tag' }, c.tagline)),
        h('span', { class: 'sr-chev', html: ARROW }));
    }
    const ch = g.chapter;
    const lessons = PL.courseLessons(c.id).filter((l) => l.chapter === ch && !l.soon);
    const done = lessons.filter((l) => PL.progress.lesson(l.id).done).length;
    return h('a', { class: 'sr-group', href: `#/course/${c.id}/${ch.num}`, 'data-hit': '', style: { '--c': c.color, '--cs': c.soft } },
      h('div', { class: 'lc-art sr-art sm', html: PL.art[ch.art] || '' }),
      h('div', { class: 'sr-group-body' },
        h('div', { class: 'sr-kick' }, h('span', { class: 'sr-course', style: { '--c': c.color } }, c.title), h('span', null, `Chapter ${ch.num} · ${plural(lessons.length, 'lesson')}`),
          done ? h('span', { class: 'sr-state' + (done === lessons.length ? ' done' : ' going') }, `${done}/${lessons.length} done`) : null),
        h('h3', null, ch.title), h('p', { class: 'sr-tag' }, ch.tagline),
        h('div', { class: 'sr-chl' }, lessons.map((l) => h('span', null, l.title)))),
      h('span', { class: 'sr-chev', html: ARROW }));
  }

  function mentionRow(r, matched) {
    const d = r.doc, meta = d.meta, s = r.steps[0];
    const [title, intro] = d.steps[s.index];
    return h('a', { class: 'sr-mention', href: lessonHref(d.id, s.index), 'data-hit': '', style: { '--c': meta.color, '--cs': meta.soft }, onClick: () => recent.add(st.q) },
      h('div', { class: 'lc-art sr-art xs', html: PL.art[d.id] || '' }),
      h('div', { class: 'sr-mention-body' },
        h('div', { class: 'sr-kick' }, courseTag(meta), h('span', null, `${d.title} · Step ${s.index + 1}`), r.stepCount > 1 ? h('span', null, `+${r.stepCount - 1} more`) : null),
        h('div', { class: 'sr-mt', html: highlight(title, matched) }),
        h('div', { class: 'sr-sni', html: snippet(intro, matched, 140) })),
      h('span', { class: 'sr-chev', html: ARROW }));
  }

  function topicChips(list) {
    return h('div', { class: 'sr-pop' }, list.map((t) => h('a', { class: 'sr-pchip', href: hashFor(t), onClick: (e) => { e.preventDefault(); setQuery(t); } }, t)));
  }

  function noResults(q, res, eng) {
    const sug = eng.suggest(q);
    return h('div', { class: 'sr-empty' },
      h('div', { class: 'sr-empty-art', 'aria-hidden': 'true' }, '🔭'),
      h('h2', null, res.partial.length ? 'Nothing covers all of that' : `No lesson on “${q}” yet`),
      sug ? h('p', null, 'Did you mean ', h('a', { href: hashFor(sug), onClick: (e) => { e.preventDefault(); setQuery(sug); } }, sug), '?') : null,
      res.partial.length ? h('div', { class: 'sr-sec' }, h('p', { class: 'sr-hintline' }, 'These lessons match some of your words:'),
        h('div', { class: 'sr-grid' }, res.partial.map((r) => card(r, res.matched)))) : null,
      h('p', { class: 'sr-hintline' }, 'Try a simpler word, or one of these:'),
      topicChips(POPULAR.slice(0, 10)));
  }

  /** Planned courses that will cover the query. `covered`: we already have lessons on it. */
  function soonNote(list, covered) {
    const byCourse = {};
    list.forEach((t) => { (byCourse[t.course] = byCourse[t.course] || []).push(t.title); });
    const names = Object.keys(byCourse);
    return h('div', { class: 'sr-soon' },
      h('span', { class: 'sr-soon-ico', html: icons.sparkle }),
      h('div', null, h('b', null, 'Coming soon. '), names.map((c, i) => {
        const topics = byCourse[c].join(', ');
        return h('span', null, i ? ' ' : '', covered
          ? ['The ', h('b', null, c), ` course will go deeper into ${topics}.`]
          : [`${topics} will get ${byCourse[c].length > 1 ? 'their own lessons' : 'its own lesson'} in the `, h('b', null, c), ' course.']);
      })));
  }

  function renderEmpty() {
    const parts = [];
    const rec = recent.list();
    if (rec.length) {
      parts.push(h('section', { class: 'sr-sec' },
        h('div', { class: 'sr-lblrow' }, h('h2', null, 'Recent searches'),
          h('button', { type: 'button', class: 'linkish', onClick: () => { recent.clear(); update(); } }, 'Clear')),
        topicChips(rec)));
    }
    const going = [];
    (PL.courses || []).filter((c) => c.status === 'live').forEach((c) => {
      const st2 = PL.ui.courseStats(c.id);
      const r = PL.resumeLesson(c.id);
      if (st2.started && r && st2.done < st2.live.length) going.push(r);
    });
    if (going.length) {
      parts.push(h('section', { class: 'sr-sec' }, h('h2', null, 'Pick up where you left off'),
        h('div', { class: 'sr-grid' }, going.map((m) => card({ doc: { id: m.id, meta: m, title: m.title, tagline: m.tagline }, steps: [] }, null)))));
    }
    parts.push(h('section', { class: 'sr-sec' }, h('h2', null, 'Popular topics'), topicChips(POPULAR)));
    parts.push(h('section', { class: 'sr-sec' }, h('h2', null, 'Or browse a course'),
      h('div', { class: 'sr-courses' }, (PL.courses || []).filter((c) => c.status === 'live').map((c) => {
        const n = PL.liveLessons(c.id).length;
        return h('a', { class: 'sr-coursecard', href: '#/course/' + c.id, style: { '--c': c.color, '--cs': c.soft } },
          h('div', { class: 'sr-cc-art', html: PL.courseArt[c.id] || '' }),
          h('div', null, h('b', null, c.title), h('span', null, `${c.chapters.length} chapters · ${n} lessons`)));
      }))));
    st.results.replaceChildren(...parts);
    st.hits = [...st.results.querySelectorAll('[data-hit]')];
  }

  function setQuery(q) {
    if (!st) return;
    st.input.value = q;
    st.q = q;
    st.c = 'all';
    st.showAll = false;
    st.clearBtn.hidden = !q;
    update();
    st.input.focus({ preventScroll: true });
    window.scrollTo({ top: 0, behavior: PL.reduced ? 'auto' : 'smooth' });
  }

  function move(dir) {
    if (!st.hits.length) return;
    st.hits.forEach((x) => x.classList.remove('kb'));
    st.active = st.active < 0 ? (dir > 0 ? 0 : st.hits.length - 1) : (st.active + dir + st.hits.length) % st.hits.length;
    const el = st.hits[st.active];
    el.classList.add('kb');
    (el.closest('.sr-best, .sr-card, .sr-mention') || el).scrollIntoView({ block: 'nearest', behavior: PL.reduced ? 'auto' : 'smooth' });
  }

  function openActive() {
    if (!st) return;
    const el = st.hits[st.active >= 0 ? st.active : 0];
    if (!el || !st.q.trim()) return;
    recent.add(st.q);
    location.hash = el.getAttribute('href');
  }

  function destroy() {
    cleanups.forEach((fn) => fn());
    cleanups = [];
    st = null;
  }

  PL.searchPage = {
    render() { render(parseHash()); },
    destroy,
    isOpen: () => !!st,
    prefetch: () => { loadIndex().catch(() => {}); },
    /** Re-run with the query in the URL, without rebuilding the page (back/forward). */
    sync() {
      const s = parseHash();
      if (!st) return render(s);
      if (s.q === st.q.trim() && s.c === st.c) return;
      st.input.value = s.q; st.q = s.q; st.c = s.c; st.clearBtn.hidden = !s.q; update();
    },
    href: hashFor,
  };

  /* "/" or Ctrl+K opens search from anywhere except inside a lesson. */
  document.addEventListener('keydown', (e) => {
    const k = e.key;
    const combo = (k === 'k' || k === 'K') && (e.ctrlKey || e.metaKey) && !e.altKey;
    if (!(combo || (k === '/' && !e.ctrlKey && !e.metaKey && !e.altKey))) return;
    const t = e.target;
    if (t && (t.isContentEditable || /^(INPUT|TEXTAREA|SELECT)$/.test(t.tagName))) return;
    if (/^#\/lesson\//.test(location.hash)) return;
    e.preventDefault();
    if (st) { st.input.focus(); st.input.select(); } else location.hash = '#/search';
  });
})();
