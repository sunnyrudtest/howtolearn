#!/usr/bin/env node
/* ==========================================================================
   Builds js/search-index.js: the text of every lesson step, plus the
   keywords and related links from tools/search-meta.js.

   Lessons are loaded on demand in the browser, so search can't read their
   steps at runtime without downloading every lesson. Instead this script runs
   each lesson file in a sandbox, keeps only the words, and writes one small
   file that the search page loads when it opens.

     node tools/build-search-index.js          write js/search-index.js
     node tools/build-search-index.js --check  fail if it is out of date
   ========================================================================== */
'use strict';
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'js', 'search-index.js');
const meta = require('./search-meta.js');

/* A stand-in for anything a lesson touches at load time (PL.h, PL.s, …). */
function stub() {
  return new Proxy(function () {}, {
    get: (t, k) => (k === Symbol.toPrimitive ? () => '' : stub()),
    apply: () => stub(),
    construct: () => stub(),
  });
}

function loadCatalogAndLessons() {
  const store = {};
  const PL = new Proxy(store, {
    get: (t, k) => (k in t ? t[k] : stub()),
    set: (t, k, v) => { t[k] = v; return true; },
  });
  const ctx = vm.createContext({ PL, console, Math, JSON, Object, Array, String, Number, Set, Map, Promise });
  ctx.window = ctx;
  vm.runInContext(fs.readFileSync(path.join(ROOT, 'js', 'courses.js'), 'utf8'), ctx, { filename: 'courses.js' });

  const catalog = {};
  for (const course of store.courses) {
    for (const ch of course.chapters || []) {
      for (const l of ch.lessons) if (l.id) catalog[l.id] = { course: course.id, chapter: ch.num, file: l.file };
    }
  }

  const lessons = {};
  store.registerLesson = (l) => { lessons[l.id] = l; };
  for (const id of Object.keys(catalog)) {
    const file = path.join(ROOT, 'js', 'lessons', catalog[id].file);
    vm.runInContext(fs.readFileSync(file, 'utf8'), ctx, { filename: catalog[id].file });
    if (!lessons[id]) throw new Error(`${catalog[id].file} did not register lesson "${id}"`);
  }
  return { catalog, lessons };
}

/* Authored text uses a tiny markdown: **bold**, *em*, `code`. Keep the words. */
const plain = (str) => String(str || '')
  .replace(/\*\*(.+?)\*\*/g, '$1')
  .replace(/(^|[\s(])\*(?!\s)(.+?)\*(?=[\s.,!?)]|$)/g, '$1$2')
  .replace(/`([^`]+)`/g, '$1')
  .replace(/\s+/g, ' ')
  .trim();

function build() {
  const { catalog, lessons } = loadCatalogAndLessons();
  const problems = [];
  const known = (id, where) => { if (!catalog[id]) problems.push(`${where}: unknown lesson id "${id}"`); return !!catalog[id]; };

  Object.keys(meta.keywords).forEach((id) => known(id, 'keywords'));
  const related = {};
  meta.related.forEach(([a, b]) => {
    if (!known(a, 'related') || !known(b, 'related')) return;
    if (a === b) { problems.push(`related: "${a}" is linked to itself`); return; }
    (related[a] = related[a] || []).includes(b) || related[a].push(b);
    (related[b] = related[b] || []).includes(a) || related[b].push(a);
  });
  Object.keys(catalog).forEach((id) => { if (!meta.keywords[id]) problems.push(`keywords: lesson "${id}" has no keywords`); });
  if (problems.length) throw new Error('search-meta.js problems:\n  ' + problems.join('\n  '));

  const out = {};
  for (const id of Object.keys(catalog)) {
    const l = lessons[id];
    out[id] = {
      k: meta.keywords[id],
      s: l.steps.map((st) => [plain(st.title), plain(st.intro)]),
      r: (l.recap || []).map(plain),
      rel: related[id] || [],
    };
  }
  return '/* Generated by tools/build-search-index.js. Do not edit by hand. */\n'
    + 'PL.searchIndex = ' + JSON.stringify({ v: 1, lessons: out }) + ';\n';
}

const text = build();
if (process.argv.includes('--check')) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (current !== text) {
    console.error('js/search-index.js is out of date. Run: node tools/build-search-index.js');
    process.exit(1);
  }
  console.log('js/search-index.js is up to date.');
} else {
  fs.writeFileSync(OUT, text);
  console.log(`Wrote js/search-index.js (${(text.length / 1024).toFixed(1)} KB, ${Object.keys(JSON.parse(text.slice(text.indexOf('{'), -2)).lessons).length} lessons).`);
}
